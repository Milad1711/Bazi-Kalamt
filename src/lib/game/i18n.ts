export const DICT: Record<Lang, Record<DictKey, string>> = { en, fa };

export function translate(lang: Lang, key: DictKey, vars?: Record<string, string | number>): string {
  let text: string = DICT[lang][key] ?? DICT.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
  }
  return text;
}

export function formatNumber(n: number, lang: Lang): string {
  return n.toLocaleString(lang === 'fa' ? 'fa-IR' : 'en-US');
}
